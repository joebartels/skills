// Command gen regenerates the default severity lookup.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	source, err := os.Open("schema.txt")
	if err != nil {
		return err
	}
	defer source.Close()
	var output bytes.Buffer
	output.WriteString("//go:build !compact\n\n// Code generated by internal/gen; DO NOT EDIT.\n\npackage severity\n\nfunc lookup(code int) string {\n switch code {\n")
	scanner := bufio.NewScanner(source)
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) != 2 {
			return fmt.Errorf("invalid schema line %q", scanner.Text())
		}
		code, err := strconv.Atoi(fields[0])
		if err != nil {
			return err
		}
		fmt.Fprintf(&output, "case %d: return %q\n", code, fields[1])
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	output.WriteString("}\nreturn \"\"\n}\n")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("table_gen.go", formatted, 0644)
}
