// Command cataloggen refreshes the validator table and the form preview data.
package main

import (
	"bytes"
	"encoding/csv"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	input, err := os.Open("formats.csv")
	if err != nil {
		return err
	}
	defer input.Close()
	records, err := csv.NewReader(input).ReadAll()
	if err != nil {
		return err
	}
	if len(records) < 2 || len(records[0]) != 4 || records[0][0] != "name" {
		return fmt.Errorf("invalid catalog header")
	}
	if err := os.MkdirAll("preview", 0755); err != nil {
		return err
	}
	var table bytes.Buffer
	table.WriteString("// Code generated by internal/cataloggen; DO NOT EDIT.\n\npackage codes\n\nfunc lookup(name string) (rule, bool) {\n switch name {\n")
	for _, record := range records[1:] {
		digits, err := strconv.Atoi(record[2])
		if err != nil || digits < 1 {
			return fmt.Errorf("invalid width for %q", record[0])
		}
		fmt.Fprintf(&table, "case %q: return rule{prefix: %q, digits: %d}, true\n", record[0], record[1], digits)
		schema := struct {
			Schema  string `json:"$schema"`
			Title   string `json:"title"`
			Type    string `json:"type"`
			Pattern string `json:"pattern"`
		}{"https://json-schema.org/draft/2020-12/schema", record[3], "string", fmt.Sprintf("^%s[0-9]{%d}$", regexp.QuoteMeta(record[1]), digits)}
		data, err := json.MarshalIndent(schema, "", "  ")
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join("preview", record[0]+".json"), append(data, '\n'), 0644); err != nil {
			return err
		}
	}
	table.WriteString("}\nreturn rule{}, false\n}\n")
	data, err := format.Source(table.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("catalog_gen.go", data, 0644)
}
